#!/usr/bin/env python3
"""Regenerates js/data.js from the CSV files in data/. Run: python tools/build_data.py"""
import csv, json, re, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, 'data')

def cost_of(name):
    m = re.search(r'\((\d+)\s*AP\)', name, re.I)
    return int(m.group(1)) if m else None

def clean_name(name):
    return re.sub(r'\s*\(\d+\s*AP\)', '', name).strip()

heroes = []
rows = list(csv.reader(open(os.path.join(D, 'roster.csv'), encoding='utf-8')))
COL = {n.strip().lower(): i for i, n in enumerate(rows[0]) if n.strip()}  # extra columns are looked up by header name (burrow)
for r in rows[1:]:
    r = r + [''] * (40 - len(r))
    num = r[21].strip()
    if not re.match(r'^\d\d/20$', num):
        continue
    nick = r[3].strip()
    full = r[5].strip()
    h = {
        'num': num, 'nick': nick, 'image': r[2].strip(),
        'blurb': r[4].strip(), 'class': r[7].strip(), 'subrole': r[8].strip(),
        'burrow': r[COL['burrow']].strip().lower() if 'burrow' in COL else '',
    }
    if full:
        h.update({'id': full.lower(), 'name': full, 'implemented': True,
                  'hp': int(r[9]), 'move': int(r[10]), 'atk': int(r[11]),
                  'reach': int(r[12]), 'ap': int(r[13]), 'abilities': []})
        for n, t in ((r[15], r[16]), (r[17], r[18]), (r[19], r[20])):
            if n.strip():
                c = cost_of(n)
                h['abilities'].append({'name': clean_name(n), 'cost': c, 'passive': c is None,
                                       'text': t.strip().replace('\\n', '\n')})
    else:
        h.update({'id': nick.lower(), 'name': nick.capitalize(), 'implemented': False,
                  'abilities': []})
    heroes.append(h)

maps = {}
mrows = list(csv.reader(open(os.path.join(D, 'maps.csv'), encoding='utf-8')))
for ci, name in [(i, c) for i, c in enumerate(mrows[2]) if c.strip()]:
    tiles = []
    for r in mrows[4:17]:
        y = int(r[ci])
        for x in range(13):
            idx = ci + 1 + x
            v = r[idx].strip() if idx < len(r) else ''
            if not v:
                continue
            m = re.match(r'^([A-Z]{2})\((.*)\)$', v)
            t = {'x': x, 'y': y, 't': v if not m else m.group(1)}
            if m and t['t'] in ('BT', 'RT'):
                a, b = m.group(2).split(',')
                t['tx'], t['ty'] = int(a), int(b)
            elif m and t['t'] == 'HG':
                a, b = [s.strip() for s in m.group(2).split(',')]
                t['hg'] = [a, b]
            tiles.append(t)
    maps[name] = tiles

for _name, _tiles in maps.items():  # warn about teleports that do not point at a teleport/anchor of their colour
    _at = {(t['x'], t['y']): t for t in _tiles}
    for t in _tiles:
        if t['t'] in ('BT', 'RT'):
            d = _at.get((t.get('tx'), t.get('ty')))
            if not d or d['t'] not in (t['t'], t['t'][0] + 'A'):
                print(f"WARNING: {_name}: teleport {t['t']} at ({t['x']},{t['y']}) points at ({t.get('tx')},{t.get('ty')}) which is not a {t['t'][0]}T/{t['t'][0]}A tile")

tiles_info = {}
for r in list(csv.reader(open(os.path.join(D, 'tiles.csv'), encoding='utf-8')))[2:]:
    if len(r) > 4 and r[1].strip():
        terr = (r[5].strip().upper() if len(r) > 5 else '') or 'NONE'  # BLU | RED | NONE | ADJACENT (see tiles.csv)
        tiles_info[r[1].strip()] = {'name': r[2].strip(), 'look': r[3].strip(), 'text': r[4].strip(), 'territory': terr}
if 'BR' in tiles_info:
    tiles_info['RA'] = tiles_info.pop('BR')  # tiles.csv calls Red Anchor "BR"; the maps use "RA"

# roles.csv: colour + description of every Role and Subrole (the colours are used on the hero chips; the text on hover)
ROLES, SUBROLES = {}, {}
for r in csv.reader(open(os.path.join(D, 'roles.csv'), encoding='utf-8')):
    r = r + [''] * (7 - len(r))
    name, desc, color, parent, like = r[1].strip(), r[2].strip(), r[3].strip(), r[5].strip(), r[6].strip()
    if not name or not re.match(r'^#[0-9a-fA-F]{6}$', color):
        continue
    if parent:
        SUBROLES[name] = {'desc': desc, 'color': color, 'parent': parent, 'like': like}
    else:
        ROLES[name] = {'desc': desc, 'color': color}

# lore_places.csv: the 7 burrows (one per built-in map, named "<Sin> Map")
PLACES = {}
for r in csv.reader(open(os.path.join(D, 'lore_places.csv'), encoding='utf-8')):
    r = r + [''] * (4 - len(r))
    sin = r[1].strip()
    if not sin or sin.lower() == 'sin':
        continue
    d = r[3].strip().rstrip(',.?! ').strip()
    PLACES[sin] = {'name': r[2].strip(), 'desc': (d[:1].upper() + d[1:]) if d else ''}

out = '// AUTO-GENERATED by tools/build_data.py from data/*.csv - do not edit by hand.\n'
out += 'export const HEROES = ' + json.dumps(heroes, indent=1, ensure_ascii=False) + ';\n'
out += 'export const MAPS = ' + json.dumps(maps, ensure_ascii=False) + ';\n'
out += 'export const TILE_INFO = ' + json.dumps(tiles_info, indent=1, ensure_ascii=False) + ';\n'
out += 'export const ROLES = ' + json.dumps(ROLES, indent=1, ensure_ascii=False) + ';\n'
out += 'export const SUBROLES = ' + json.dumps(SUBROLES, indent=1, ensure_ascii=False) + ';\n'
out += 'export const PLACES = ' + json.dumps(PLACES, indent=1, ensure_ascii=False) + ';\n'
open(os.path.join(ROOT, 'js', 'data.js'), 'w', encoding='utf-8').write(out)
print('heroes', len(heroes), 'maps', {k: len(v) for k, v in maps.items()})
